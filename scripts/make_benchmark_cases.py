"""Write benchmark/<id>.yaml from docs/benchmark_evidence/evidence.json (no hand-typed
residues or IDs). Re-run after rebuilding the evidence:  python scripts/make_benchmark_cases.py
"""
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
ev = json.loads((ROOT / "docs/benchmark_evidence/evidence.json").read_text(encoding="utf-8"))
# protein order follows docs/benchmark_design.md section 2; queries are the ones in the evidence file
ORDER = {"1FIN": ("P24941", "P20248"), "4G0N": ("P01112", "P04049"), "1YCR": ("Q00987", "P04637"),
         "1BXL": ("Q07817", "Q16611"), "1AXC": ("P12004", "P38936")}

out = ROOT / "benchmark"
out.mkdir(exist_ok=True)
for pdb, (a, b) in ORDER.items():
    c = ev["cases"][pdb]
    pa, pb = c["proteins"][a], c["proteins"][b]
    na, nb = pa["uniprot_id"].split("_")[0], pb["uniprot_id"].split("_")[0]
    cid = f"{na.lower()}_{nb.lower()}"
    goal = (f"Investigate where {pa['name']} (UniProt {a}) and {pb['name']} (UniProt {b}) bind each "
            f"other. Use the tools to gather evidence, then predict for EACH protein the region of "
            f"its sequence that forms the interface (UniProt numbering). Tools with no data report "
            f"'pending'; never invent residues or scores. Submit with submit_adjudication and "
            f"fill predicted_regions.")
    doc = {"id": cid, "name_a": na, "uniprot_a": a, "name_b": nb, "uniprot_b": b, "benchmark": True,
           "md_scores": None, "literature_query": c["literature_query"]["term"], "goal": goal,
           "ground_truth": {"pdb": pdb, "source": "docs/benchmark_evidence/evidence.json",
                            "interface_residues": {a: pa["interface_residues"], b: pb["interface_residues"]}}}
    (out / f"{cid}.yaml").write_text(
        "# GENERATED by scripts/make_benchmark_cases.py from docs/benchmark_evidence/evidence.json.\n"
        "# ground_truth is read by the scorer and the leak filter only, never shown to the agent.\n"
        + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=100), encoding="utf-8")
    print("wrote", f"benchmark/{cid}.yaml")
